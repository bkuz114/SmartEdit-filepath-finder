# Extract the package version from __init__.py
#
# Parses the __version__ assignment from the package's __init__.py file,
# which serves as the single source of truth for the version number.
#
# Expected format in __init__.py:
#   __version__ = "4.0.0"
#
# The function tolerates:
#   - Leading/trailing whitespace around the assignment
#   - Single or double quotes around the version string
#   - The version string containing pre-release/build suffixes (e.g., "4.0.0rc1")
#
# Args:
#   $1 - init_file: Full path to the package's __init__.py file
#
# Outputs:
#   The version string (e.g., "4.0.0") on stdout
#
# Returns:
#   0 if the version was successfully extracted
#   1 if no __version__ assignment could be found
#
# Usage:
#   VERSION="$(get_version "${REPO_ROOT}/src/${PROJECT_NORMALIZED}/__init__.py")"
#
# Notes:
#   - Uses grep + sed rather than importing the module, as importing would
#     execute arbitrary package code during the build process.
#   - The grep pattern anchors to the literal string '__version__' at the
#     start of the line, allowing optional surrounding whitespace.
get_version() {
    local init_file="$1"
    local version

    # Check the file exists before attempting to parse it
    if [[ ! -f "${init_file}" ]]; then
        echo "ERROR: Cannot determine version — ${init_file} does not exist" >&2
        return 1
    fi

    # Extract the version string:
    #   grep  : match lines starting with optional whitespace, then '__version__',
    #           then optional whitespace, '=', then optional whitespace,
    #           then a single or double quoted string.
    #   sed   : extract the contents of the quoted string (the version value).
    #
    # The '|| return 1' ensures we fail loudly if grep finds no match,
    # rather than silently continuing with an empty version.
    version="$(grep -E '^[[:space:]]*__version__[[:space:]]*=[[:space:]]*["'"'"'][^"'"'"']+["'"'"']' "${init_file}" \
        | sed -E 's/^[[:space:]]*__version__[[:space:]]*=[[:space:]]*["'"'"']([^"'"'"']+)["'"'"'].*$/\1/' \
        || return 1)"

    # Verify we actually got a non-empty result
    if [[ -z "${version}" ]]; then
        echo "ERROR: Could not parse __version__ from ${init_file}" >&2
        return 1
    fi

    echo "${version}"
}

